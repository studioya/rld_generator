"""
1. Every sample parses completely (all objects consumed, 48-byte trailer left).
2. Every vector and bitmap sample is rebuilt by src/rldwriter.py from its parsed
   contents and compared with the original. Bytes RDWorks fills with leftover
   memory are masked; float bboxes may differ in the last bit.
3. Files generated by the writer and re-saved by RDWorks come back unchanged.

Run:  python3 tests/test_roundtrip.py
"""
import copy, glob, os, struct, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [os.path.join(ROOT, "src"), os.path.join(ROOT, "tools")]
import rldwriter as W, rld_parse as P

S = lambda *p: os.path.join(ROOT, "samples", *p)
REBUILD = sorted(glob.glob(S("batch1", "t[2-6].rld")) + glob.glob(S("batch2", "b*.rld")) +
                 glob.glob(S("batch3", "saved", "*.rld")))
SKIP = ("b28", "b30", "b33", "c30", "c31", "c32", "c33", "c40", "c41")   # text & groups: parse-only


def mask(b, objs):
    b = bytearray(b)
    def walk(ob):
        if ob["type"] == "path":
            p = ob["start"] + 53
            for i, (k, _) in enumerate(ob["segs"]):
                q = p + i * 74
                b[q + 2:q + 6] = bytes(4)
                if k == "L": b[q + 38:q + 70] = bytes(32)
        for c in ob.get("children", []): walk(c)
    for ob in objs: walk(ob)
    return bytes(b)


def rebuild(b, tpl):
    hdr, layers, objs, _ = P.parse(b)
    t = copy.copy(tpl); t.prefix = bytearray(b[:hdr["sec"]]); t.table = hdr["table"]
    Ls, vpos, bpos = [], {}, None
    for i, L in enumerate(layers):
        common = {k: L[k] for k in ("speed", "min", "max", "min2", "max2", "mode", "output", "air")}
        if L["bitmap"]:
            Ls.append(dict(bitmap=True, **common)); bpos = i
        else:
            pal = next(j for j in range(256) if b[t.table + j * W.REC:t.table + j * W.REC + 4].hex() == L["color"])
            Ls.append(dict(palette=pal, bidir=L["bidir"], interval=L["interval"], **common)); vpos[L["color"]] = i
    shapes = []
    for ob in objs:
        if ob["type"] == "bitmap":
            shapes.append((bpos, W.Bitmap(ob["bmp"], ob["center"]), True))
        else:
            shapes.append((vpos[ob["color"]], ob["segs"], bool(ob["closed"])))
    return W.build(t, Ls, shapes)


def close_enough(a, b):
    """Same objects; numbers equal to 1e-9 (RDWorks' own float rounding)."""
    _, La, Oa, ra = P.parse(a); _, Lb, Ob, rb = P.parse(b)
    if ra != rb or len(Oa) != len(Ob): return False
    for x, y in zip(Oa, Ob):
        if x["type"] != y["type"] or any(abs(p - q) > 1e-9 for p, q in zip(x["bbox"], y["bbox"])): return False
    return True


if __name__ == "__main__":
    tpl = W.Template(S("batch1", "t1.rld"), glob.glob(S("batch2", "b00_*.rld"))[0])
    fails = 0
    allfiles = sorted(glob.glob(S("**", "*.rld"), recursive=True))
    for p in allfiles:
        rest = P.parse(open(p, "rb").read())[3]
        if rest != 48: fails += 1; print("PARSE FAIL", p, rest)
    print(f"parse: {len(allfiles)} files")
    for p in REBUILD:
        name = os.path.basename(p).split("_")[0].removesuffix(".rld")
        if name in SKIP: continue
        b = open(p, "rb").read(); out = rebuild(b, tpl)
        exact = out == b
        ok = exact or mask(out, P.parse(out)[2]) == mask(b, P.parse(b)[2]) or close_enough(out, b)
        fails += not ok
        print(f"rebuild {name:5} {'exact' if exact else 'ok (junk/float only)' if ok else 'FAIL'}")
    for g in sorted(glob.glob(S("batch3", "generated", "g*.rld"))):
        r = S("batch3", "resaved", os.path.basename(g)[:3] + "_resaved.rld")
        same = open(g, "rb").read() == open(r, "rb").read()
        fails += not same
        print(f"RDWorks re-save {os.path.basename(g)[:3]}: {'identical' if same else 'CHANGED'}")
    print("FAIL" if fails else "PASS")
    sys.exit(1 if fails else 0)
